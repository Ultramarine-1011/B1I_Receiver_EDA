# Generate or check student_release/student_release/rtl/fft_twiddle_rom.svh
# from the original fft_cos_q30.mem and fft_sin_q30.mem tables.
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
ROM = ROOT / "student_release" / "student_release" / "rom"
RTL = ROOT / "student_release" / "student_release" / "rtl"
OUT = RTL / "fft_twiddle_rom.svh"
DEPTH = 4096


def load_words(path):
    words = []
    for line in path.read_text(encoding="ascii").splitlines():
        text = line.strip()
        if not text or text.startswith("//"):
            continue
        words.append(int(text, 16))
    if len(words) != DEPTH:
        raise SystemExit("%s has %d words, expected %d" % (path, len(words), DEPTH))
    return words


def function_text(name, words):
    lines = [
        "function signed [31:0] %s;" % name,
        "    input [11:0] addr;",
        "    begin",
        "        case (addr)",
    ]
    for index, word in enumerate(words):
        lines.append("            12'h%03X: %s = 32'sh%08x;" % (index, name, word))
    lines.extend([
        "            default: %s = 32'sh00000000;" % name,
        "        endcase",
        "    end",
        "endfunction",
        "",
    ])
    return "\n".join(lines)


def render(cos_words, sin_words):
    return "\n".join([
        "// Generated by scripts/gen_fft_twiddle_rom.py from",
        "// rom/fft_cos_q30.mem and rom/fft_sin_q30.mem.",
        "// Q30 two's-complement values are unchanged. The case function is the",
        "// coding Design Compiler K-2015.06 kept in the M2 mapped netlist;",
        "// initial $readmemh was ignored (VER-281).",
        "",
        function_text("fft_twiddle_cos", cos_words),
        function_text("fft_twiddle_sin", sin_words),
    ])


def main():
    cos_words = load_words(ROM / "fft_cos_q30.mem")
    sin_words = load_words(ROM / "fft_sin_q30.mem")
    text = render(cos_words, sin_words)
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="ascii")
        if current != text:
            raise SystemExit("fft_twiddle_rom.svh does not match the mem tables")
        print("FFT_TWIDDLE_ROM_MATCH words=%d" % DEPTH)
        return
    OUT.write_text(text, encoding="ascii", newline="\n")
    print("WROTE %s bytes=%d" % (OUT, len(text)))


if __name__ == "__main__":
    main()
