"""Prove and generate exact reciprocal divisions without a remainder correction chain."""
import json
from pathlib import Path
import re
import tarfile

EXPERIMENT = Path(__file__).resolve().parent.parent
source = (EXPERIMENT.parent / "History/TSMC90_V1_V4/rtl/tracking_channel_minimal.sv").read_text(encoding="utf-8")
bounds = []
signed_source = source
for divisor, width, name in ((127875, 40, "step_127875"), (763, 33, "aid_763")):
    maximum = 1 << (width-1)
    for shift in range(width, 2*width):
        scale = 1 << shift
        multiplier = (scale+divisor-1)//divisor
        error = divisor*multiplier-scale
        quotient, remainder = divmod(maximum, divisor)
        # x=qD+r. The excess q*error+r*M is maximized at the last complete
        # quotient interval or the final partial interval, since error>=0.
        bound = max((quotient-1)*error+(divisor-1)*multiplier,
                    quotient*error+remainder*multiplier)
        if bound < scale:
            break
    else:
        raise RuntimeError("No exact reciprocal found")
    bits = multiplier.bit_length()
    bounds.append(dict(divisor=divisor, width=width, maximum_magnitude=maximum,
                       shift=shift, multiplier=multiplier, reciprocal_error=error,
                       maximum_excess=bound, scale=scale,
                       proof="max(q*error+r*M)<2^shift over all 0<=x<=2^(W-1)"))
    function = f"""    // Exact ceil reciprocal over the entire signed {width}-bit input domain.
    // The quotient-bound proof is generated by prepare_constants.py.
    function automatic logic signed [23:0] divide_{name}(input logic signed [{width-1}:0] value);
        logic [{width-1}:0] magnitude;
        logic [{width+bits-1}:0] product;
        logic [23:0] quotient;
        begin
            magnitude=value[{width-1}] ? (~value+{width}'d1) : value;
            product=magnitude*{bits}'d{multiplier};
            quotient=24'(product >> {shift});
            divide_{name}=value[{width-1}] ? -$signed(quotient) : $signed(quotient);
        end
    endfunction"""
    source = re.sub(
        rf"    function automatic logic signed \[23:0\] divide_{name}\([\s\S]*?    endfunction",
        lambda _: function, source)
    assert multiplier % 2 == 1 and maximum < scale
    signed_function = f"""    // For x<0 the odd reciprocal product is strictly between two 2^{shift} multiples.
    // Arithmetic truncation plus one therefore implements division toward zero.
    function automatic logic signed [23:0] divide_{name}(input logic signed [{width-1}:0] value);
        logic signed [{width+bits}:0] product;
        logic signed [23:0] floor_quotient;
        begin
            product=value*{bits+1}'sd{multiplier};
            floor_quotient=24'(product >>> {shift});
            divide_{name}=floor_quotient+24'(value[{width-1}]);
        end
    endfunction"""
    signed_source = re.sub(
        rf"    function automatic logic signed \[23:0\] divide_{name}\([\s\S]*?    endfunction",
        lambda _: signed_function, signed_source)
(EXPERIMENT / "work/tracking_channel_constants.sv").write_text(source, encoding="utf-8")
(EXPERIMENT / "work/tracking_channel_signed.sv").write_text(signed_source, encoding="utf-8")
(EXPERIMENT / "evidence/reciprocal_bounds.json").write_text(json.dumps(bounds, indent=2), encoding="utf-8")

# Reuse the established conversion probe and its clamped input domains.
with tarfile.open(EXPERIMENT / "evidence/module_dc.tar.gz", "r:gz") as archive:
    captured = archive.extractfile("probe_sources/conversion_probes.sv").read().decode("utf-8")
v4 = captured.split("module conversion_fast", 1)[0].rstrip() + "\n"
fast = v4.replace("module conversion_v4", "module conversion_fast", 1)
signed = v4.replace("module conversion_v4", "module conversion_signed", 1)
for name in ("step_127875", "aid_763"):
    pattern = rf"    function automatic logic signed \[23:0\] divide_{name}\([\s\S]*?    endfunction"
    fast = re.sub(pattern, lambda _: re.search(pattern, source)[0], fast)
    signed = re.sub(pattern, lambda _: re.search(pattern, signed_source)[0], signed)
(EXPERIMENT / "work/conversion_probes.sv").write_text(v4+"\n"+fast+"\n"+signed, encoding="utf-8")

tcl = (EXPERIMENT / "scripts/dc_radix.tcl").read_text(encoding="utf-8")
tcl = tcl.replace("work/radix_probes.sv", "work/conversion_probes.sv")
